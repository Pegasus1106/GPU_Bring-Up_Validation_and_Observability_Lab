"""Build the fixed input set and manifest (manifests/inputs.json).

Default: 256 deterministic *synthetic* procedural images (CC0, generated here).
They are valid for latency/throughput, API and numerical-equivalence testing
(CPU vs GPU on identical tensors). They are NOT valid for classification
accuracy claims; the manifest says so explicitly.

To use real, licensed, non-personal images instead:
    python -m manifests.build_inputs --source-dir /path/to/images \
        --license "CC0 / your licence text" --count 256
Images are copied unmodified (file bytes hashed), ordered by file name.
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from common.util import REPO_ROOT, git_commit, iso, sha256_file, write_json

SIZE = 256


def synth_image(i: int) -> Image.Image:
    rng = np.random.default_rng(1000 + i)
    yy, xx = np.mgrid[0:SIZE, 0:SIZE].astype(np.float32) / SIZE
    c0, c1 = rng.uniform(0, 255, 3), rng.uniform(0, 255, 3)
    ang = rng.uniform(0, np.pi)
    t = (np.cos(ang) * xx + np.sin(ang) * yy)[..., None]
    img = (c0 * (1 - t) + c1 * t).astype(np.float32)
    # low-frequency texture
    fx, fy = rng.uniform(2, 9, 2)
    img += 25 * np.sin(2 * np.pi * (fx * xx + fy * yy) + rng.uniform(0, 6.28))[..., None] * rng.uniform(0.3, 1.0, 3)
    im = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "RGB")
    d = ImageDraw.Draw(im)
    for _ in range(int(rng.integers(3, 9))):
        x0, y0 = rng.integers(0, SIZE - 40, 2)
        w, h = rng.integers(20, 120, 2)
        col = tuple(int(v) for v in rng.integers(0, 256, 3))
        box = [int(x0), int(y0), int(min(SIZE - 1, x0 + w)), int(min(SIZE - 1, y0 + h))]
        (d.ellipse if rng.random() < 0.5 else d.rectangle)(box, fill=col)
    return im


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=256)
    ap.add_argument("--source-dir", type=Path, default=None)
    ap.add_argument("--license", default="CC0-1.0 (procedurally generated by manifests/build_inputs.py)")
    ap.add_argument("--out-dir", type=Path, default=REPO_ROOT / "manifests/inputs")
    ap.add_argument("--manifest", type=Path, default=REPO_ROOT / "manifests/inputs.json")
    a = ap.parse_args()

    a.out_dir.mkdir(parents=True, exist_ok=True)
    items = []
    if a.source_dir:
        files = sorted(p for p in a.source_dir.iterdir() if p.suffix.lower() in (".png", ".jpg", ".jpeg"))
        if len(files) < a.count:
            raise SystemExit(f"only {len(files)} images in {a.source_dir}, need {a.count}")
        for i, src in enumerate(files[: a.count]):
            dst = a.out_dir / f"img_{i:03d}{src.suffix.lower()}"
            shutil.copyfile(src, dst)
            items.append((i, dst))
        synthetic = False
    else:
        for i in range(a.count):
            dst = a.out_dir / f"img_{i:03d}.png"
            synth_image(i).save(dst, format="PNG", optimize=True)
            items.append((i, dst))
        synthetic = True

    write_json(
        a.manifest,
        {
            "version": 1,
            "created_utc": iso(),
            "created_by_commit": git_commit(),
            "count": len(items),
            "synthetic": synthetic,
            "suitable_for_accuracy_claims": not synthetic,
            "license": a.license,
            "contains_personal_data": False,
            "preprocessing_file": "preprocessing.json",
            "items": [
                {
                    "id": f"img_{i:03d}",
                    "file": p.name,
                    "sha256": sha256_file(p),
                    "bytes": p.stat().st_size,
                }
                for i, p in items
            ],
        },
    )
    print(f"wrote {len(items)} inputs ({'synthetic' if synthetic else 'real'}) -> {a.manifest}")


if __name__ == "__main__":
    main()
