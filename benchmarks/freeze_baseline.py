"""Freeze matching-baseline p95 latencies into a Prometheus recording-rule file.

LatencyRegression compares the live p95 against `2 x lab_baseline_p95_seconds`
for the same (backend, batch_size). The baseline must come from the *same load
profile* as the fault drills (default: concurrency 4), so we freeze exactly that
slice of the benchmark summary.

    python -m benchmarks.freeze_baseline --summary artifacts/benchmark/<id>/summary.json --concurrency 4
"""
from __future__ import annotations

import argparse
from pathlib import Path

from common.util import REPO_ROOT, git_commit, iso, read_json, write_json

OUT = REPO_ROOT / "monitoring/rules/baseline.yml"
BACKEND_LABEL = {"cpu": "cpu", "gpu": "cuda"}  # matrix backend name -> service `backend` label


def build_rules(summary: dict, concurrency: int, trials_min: int = 3) -> tuple[str, dict]:
    lines = [
        "# GENERATED by benchmarks/freeze_baseline.py - do not edit by hand.",
        f"# source: {summary['experiment_id']}  commit: {git_commit()}  frozen: {iso()}  concurrency: {concurrency}",
        "# Each series is the mean-over-trials client p95 (seconds) for the matching baseline cell.",
        "groups:",
        "  - name: lab-baseline",
        "    interval: 5s",
        "    rules:",
    ]
    frozen = {}
    for cid, c in sorted(summary["cells"].items()):
        backend, bs, conc = cid.split("-")
        if int(conc[1:]) != concurrency:
            continue
        p95 = c["p95_ms"]["mean"]
        if p95 is None or c["p95_ms"]["n"] < trials_min:
            continue
        label = BACKEND_LABEL[backend]
        bsz = bs[1:]
        sec = p95 / 1000.0
        lines += [
            "      - record: lab_baseline_p95_seconds",
            f"        expr: vector({sec:.6f})",
            f'        labels: {{backend: "{label}", batch_size: "{bsz}", workload: "resnet18"}}',
        ]
        frozen[cid] = sec
    if not frozen:
        return "groups: []\n", {}
    return "\n".join(lines) + "\n", frozen


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", type=Path, required=True)
    ap.add_argument("--concurrency", type=int, default=4)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    text, frozen = build_rules(read_json(a.summary), a.concurrency)
    a.out.write_text(text)
    write_json(a.out.with_suffix(".json"), {"frozen_utc": iso(), "source": str(a.summary), "concurrency": a.concurrency, "p95_seconds": frozen})
    print(f"froze {len(frozen)} baseline series -> {a.out}")
    return 0 if frozen else 1


if __name__ == "__main__":
    raise SystemExit(main())
